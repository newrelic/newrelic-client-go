package nrqlmacros

import "encoding/json"

// This file supplies the few items that tutone cannot generate for the nrqlmacros package:
//
// 1. EntityManagementNRQLMacroEntity{Create,Update}{Input,Result} — these four types are
//    absent from the NerdGraph schema introspection dump entirely (same gap as the
//    scorecards hierarchy-level mutations documented above the scorecards entry in
//    .tutone.yml). The mutations themselves work fine; only the schema registration is
//    missing.  Hand-write the types here until the platform team fixes the schema export.
//
// 2. UnmarshalJSON for EntityManagementActorStitchedFields — tutone generates this in
//    packages where it processes a richer set of entity types (e.g. pipelinecontrol),
//    but omits it here. Without it GetEntity always returns a JSON decode error because
//    the Entity field is an interface. Mirrors the same fix in pkg/servicearchintelligence.
//
// All other types (ScopedReferenceInput, TagInput, EntityManagementEntityScope) are now
// generated by tutone via explicit entries in the .tutone.yml types block.
//
// Regenerating pkg/nrqlmacros should leave this file intact.

// EntityManagementNRQLMacroEntityCreateInput is the input for creating a NRQL macro.
type EntityManagementNRQLMacroEntityCreateInput struct {
	// The NRQL expression fragment that this macro expands to. Required.
	Expression string `json:"expression"`
	// A unique, human-readable name for the macro. Immutable after creation. Required.
	Name string `json:"name"`
	// Number of positional parameters ($1, $2, ...) used in the expression. Optional.
	// Zero means no parameters.
	NumParameters int `json:"numParameters,omitempty"`
	// The scope of the macro. Only ORGANIZATION scope is currently supported. Required.
	Scope EntityManagementScopedReferenceInput `json:"scope"`
	// Optional key-value tags to associate with the macro.
	Tags []EntityManagementTagInput `json:"tags,omitempty"`
}

// EntityManagementNRQLMacroEntityUpdateInput is the input for updating a NRQL macro.
// Only expression, numParameters, and tags are mutable after creation.
// Name and scope are immutable and absent from this type intentionally.
//
// Note: NumParameters uses int rather than *int. The API treats the absence of the field
// the same as zero, so there is no need to distinguish "not provided" from "set to zero"
// in practice. If that changes, swap to *int and drop omitempty.
type EntityManagementNRQLMacroEntityUpdateInput struct {
	// The updated NRQL expression fragment. Omit to leave unchanged.
	Expression string `json:"expression,omitempty"`
	// Updated parameter count. Omit to leave unchanged.
	NumParameters int `json:"numParameters,omitempty"`
	// Updated tags. Omit to leave unchanged.
	Tags []EntityManagementTagInput `json:"tags,omitempty"`
}

// EntityManagementNRQLMacroEntityCreateResult holds the result of a create mutation.
type EntityManagementNRQLMacroEntityCreateResult struct {
	Entity EntityManagementNRQLMacroEntity `json:"entity"`
}

// EntityManagementNRQLMacroEntityUpdateResult holds the result of an update mutation.
type EntityManagementNRQLMacroEntityUpdateResult struct {
	Entity EntityManagementNRQLMacroEntity `json:"entity"`
}

// UnmarshalJSON provides custom JSON decoding for EntityManagementActorStitchedFields.
// The Entity field is an interface; Go's default decoder cannot dispatch it without
// knowing the concrete type at decode time. This mirrors the "DO NOT DELETE" function
// that tutone generates in pkg/pipelinecontrol/types.go but omits in this package.
func (x *EntityManagementActorStitchedFields) UnmarshalJSON(b []byte) error {
	var objMap map[string]*json.RawMessage
	if err := json.Unmarshal(b, &objMap); err != nil {
		return err
	}

	for k, v := range objMap {
		if v == nil {
			continue
		}
		switch k {
		case "entity":
			xxx, err := UnmarshalEntityManagementEntityInterface(*v)
			if err != nil {
				return err
			}
			if xxx != nil {
				x.Entity = *xxx
			}
		case "entitySearch":
			if err := json.Unmarshal(*v, &x.EntitySearch); err != nil {
				return err
			}
		}
	}
	return nil
}
